"""L4.1 Problem Formulator (GOAL §5 L4 stage 1; review ST-14 / E16): anomaly-first, on DEV data only, through a
declared cell grammar, with the look-elsewhere cost paid in yield on dev and never in held-out budget.

How it works (every step is deterministic code; no model call):

1. **Declared grammar, fixed before the scan.** A `CellGrammar` names the feature columns that may define subgroups
   (categorical levels or numeric quantile bins), how many conditions a cell may combine (1 or 2), the response(s)
   scanned (`target`: the outcome itself; `baseline_error`: the baseline's out-of-fold dev error), the minimum cell
   size, the scan-level alpha, the number of permutations and the permutation seed. Cells are built from FEATURE
   values only, never from the response, so permuting the response is a valid null for every cell. The scan size M
   (cells x responses) is counted by code. A cell that is not generated by the grammar is not a candidate
   (`check_in_grammar`): an "I noticed something" idea from a model goes to the idea pool, with no Kernel path
   (the forking-paths fix of the maverick review).
   `formulate_from_vault` commits the grammar to the Kernel ledger (a `register_artifact` entry of kind
   `formulator-grammar`) BEFORE it reads the dev bytes, so the order is on the record.
2. **Look-elsewhere correction by a permutation-max null on dev.** For each permutation of the response rows (the
   rows of all responses are permuted together), the statistic of every cell is recomputed and the maximum over the
   whole scan is kept. A cell's scan-adjusted p-value is (1 + #{b : max_b >= stat_cell}) / (B + 1); it is a
   candidate only if that p is <= alpha. Under the global null (responses exchangeable with respect to the features)
   the chance that the scan yields ANY candidate is <= alpha (exact Monte Carlo permutation test of the maximum;
   ties count against the cell, which is conservative). The cost of scanning many cells is therefore a higher bar on
   dev (fewer candidates: yield), never an extra held-out alpha slot: each candidate that is later pursued is ONE
   pre-registered claim against one slot (trials factor 1 at confirmation).
3. **Typed candidates, ranked by tier x value x feasibility.** `CandidateProblem` carries the cell, the dev effect,
   z, the scan-adjusted p, the scan size and the grammar digest. `priority = tier_weight(best available verifier
   tier) * value * feasibility`:
   - tier: the strongest tier a claim about the candidate could reach with the verifiers available NOW. For these
     data candidates that is T2 if a human-approved adapter serves the evidence class and metric (K1's own
     `adapters.resolve`), else T6 (priority 0; still listed, so the gap is visible);
   - value, in [0, 1]: for a mismatch baseline-error pocket, the share of ALL dev rows that would become correct if
     the pocket's error rate fell to the rest's (metric units of accuracy); otherwise the share of the response's
     dev variance the cell explains (eta squared, f (1 - f) effect^2 / var);
   - feasibility, in [0, 1]: the normal-approximation power of a one-sided confirmation at `confirm_alpha` on
     `n_confirm` rows (default: the dev size) at the dev effect. This is OPTIMISTIC: the dev effect of a selected
     maximum is biased upward (winner's curse), so feasibility ranks candidates; it is not a forecast.
   Ranking steers budget (which candidate gets a slot first). It never accepts anything: a candidate is a
   hypothesis (`status="hypothesis"`), and only the Kernel's held-out checks can certify a claim built from it.
4. **Never reads held-out data.** `formulate_from_vault` refuses any dataset whose role is not `dev`, and refuses a dev
   file whose bytes equal a file of a held-out dataset (relabelled held-out data), BEFORE fetching any bytes. It reads
   only public dev files (`read_public`); it has no code path that reads a private file.

Not built (honest): literature-mined problems and failed replications (GOAL L4.1 lists them) need the literature
graph; no offline fixtures of open problems exist in this repository, so this module mines data anomalies only.
Not wired into the research loop yet (no `research.formulate` node): see the mailbox post for the hooks it needs.
"""

