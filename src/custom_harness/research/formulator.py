class FormulatorError(ValueError):
    """The scan is refused (undeclared or invalid grammar, a non-dev dataset, unusable data)."""


# ---------------------------------------------------------------- grammar
class _Frozen(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class FeatureRule(_Frozen):
    """One column that may define subgroups. Categorical: one atom per observed level (`column == level`); numeric:
    one atom per quantile bin (`lo < column <= hi`, cut points from the dev feature values). Unparsable or empty
    numeric values belong to no bin."""

    column: str
    kind: Literal["categorical", "numeric"]
    bins: int = Field(default=DEFAULTS.numeric_bins, ge=2, le=20)


ResponseKind = Literal["target", "baseline_error"]


class CellGrammar(_Frozen):
    """What the scan may look at, declared before the scan. `digest()` identifies it on the record."""

    target: str
    features: tuple[FeatureRule, ...] = Field(min_length=1)
    responses: tuple[ResponseKind, ...] = ("target",)
    # how a non-numeric target becomes a number: the indicator of this level (required for a non-numeric target)
    target_level: str | None = None
    # baseline_error: `mismatch` = prediction != label (classification); `absolute` = |prediction - label|
    error: Literal["mismatch", "absolute"] = "mismatch"
    max_conditions: Literal[1, 2] = 1
    min_cell: int = Field(default=DEFAULTS.min_cell, ge=2)
    alpha: float = Field(default=DEFAULTS.scan_alpha, gt=0, lt=1)
    permutations: int = Field(default=DEFAULTS.permutations, ge=19)
    seed: int = 0

    @model_validator(mode="after")
    def _check(self) -> CellGrammar:
        cols = [f.column for f in self.features]
        if len(set(cols)) != len(cols):
            raise ValueError("a feature column is declared twice")
        if self.target in cols:
            raise ValueError("the target column cannot define subgroups (cells must not depend on the response)")
        if len(set(self.responses)) != len(self.responses) or not self.responses:
            raise ValueError("responses must be distinct and non-empty")
        return self

    def digest(self) -> str:
        return hashlib.sha256(json.dumps(self.model_dump(mode="json"), sort_keys=True,
                                         separators=(",", ":")).encode()).hexdigest()


class Condition(_Frozen):
    column: str
    op: Literal["eq", "bin"]
    level: str | None = None  # eq
    lo: float | None = None  # bin: lo < x <= hi (None = unbounded)
    hi: float | None = None

    def text(self) -> str:
        if self.op == "eq":
            return f"{self.column} == {self.level!r}"
        lo = "-inf" if self.lo is None else f"{self.lo:.6g}"
        hi = "+inf" if self.hi is None else f"{self.hi:.6g}"
        return f"{self.column} in ({lo}, {hi}]"


@dataclass(frozen=True)
class _Cell:
    conditions: tuple[Condition, ...]
    members: tuple[int, ...]

    @property
    def key(self) -> str:
        return " AND ".join(c.text() for c in self.conditions)


def _revalidate(grammar: CellGrammar) -> CellGrammar:
    """`model_copy(update=...)` skips pydantic validation: every entry point re-validates the declaration."""
    return CellGrammar.model_validate(grammar.model_dump())


def _num(v: str) -> float | None:
    try:
        x = float(v)
    except (TypeError, ValueError):
        return None
    return x if math.isfinite(x) else None


def _atoms(rule: FeatureRule, values: list[str]) -> list[_Cell]:
    if rule.kind == "categorical":
        levels = sorted(set(values))
        return [_Cell((Condition(column=rule.column, op="eq", level=lv),),
                      tuple(i for i, v in enumerate(values) if v == lv)) for lv in levels]
    xs = [_num(v) for v in values]
    present = sorted(x for x in xs if x is not None)
    if not present:
        return []
    cuts = sorted({present[min(len(present) - 1, (i * len(present)) // rule.bins)] for i in range(1, rule.bins)})
    edges: list[float | None] = [None, *cuts, None]
    out = []
    for lo, hi in pairwise(edges):
        mem = tuple(i for i, x in enumerate(xs) if x is not None and (lo is None or x > lo) and (hi is None or x <= hi))
        out.append(_Cell((Condition(column=rule.column, op="bin", lo=lo, hi=hi),), mem))
    return out


def enumerate_cells(grammar: CellGrammar, header: list[str], rows: list[list[str]]) -> tuple[list[_Cell], int]:
    """The cells the grammar generates on these rows, from FEATURE columns only. Returns (scannable cells, number
    excluded for size). Cells with the same members are kept once (the first in enumeration order)."""
    grammar = _revalidate(grammar)
    idx = {c: i for i, c in enumerate(header)}
    missing = [f.column for f in grammar.features if f.column not in idx]
    if missing:
        raise FormulatorError(f"declared feature column(s) not in the data: {missing}")
    per_feature = [_atoms(f, [r[idx[f.column]] for r in rows]) for f in grammar.features]
    cells = [a for atoms in per_feature for a in atoms]
    if grammar.max_conditions == 2:
        for fa, fb in combinations(range(len(per_feature)), 2):
            for a in per_feature[fa]:
                sa = set(a.members)
                for b in per_feature[fb]:
                    cells.append(_Cell(a.conditions + b.conditions, tuple(i for i in b.members if i in sa)))
    n = len(rows)
    seen: set[tuple[int, ...]] = set()
    kept, excluded = [], 0
    for c in cells:
        m = len(c.members)
        if m < grammar.min_cell or n - m < grammar.min_cell:
            excluded += 1
            continue
        if c.members in seen:
            continue
        seen.add(c.members)
        kept.append(c)
    return kept, excluded


def check_in_grammar(conditions: list[dict[str, Any]] | tuple[Condition, ...], grammar: CellGrammar,
                     header: list[str], rows: list[list[str]]) -> bool:
    """True only if these conditions are exactly a cell the grammar generates on these rows. A proposed cell that is
    not (an undeclared column, a hand-picked cut point, three conditions) is refused: it has no Kernel path."""
    want = tuple(c if isinstance(c, Condition) else Condition.model_validate(c) for c in conditions)
    cells, _ = enumerate_cells(grammar, header, rows)
    return any(c.conditions == want for c in cells)


# ---------------------------------------------------------------- statistics
def _responses(grammar: CellGrammar, header: list[str], rows: list[list[str]],
               baseline_predictions: list[str] | None) -> dict[ResponseKind, list[float]]:
    if grammar.target not in header:
        raise FormulatorError(f"target column {grammar.target!r} not in the data")
    ti = header.index(grammar.target)
    y_raw = [r[ti] for r in rows]
    out: dict[ResponseKind, list[float]] = {}
    for kind in grammar.responses:
        if kind == "target":
            ys = [_num(v) for v in y_raw]
            if grammar.target_level is not None:
                out[kind] = [1.0 if v == grammar.target_level else 0.0 for v in y_raw]
            elif all(y is not None for y in ys):
                out[kind] = [float(y) for y in ys if y is not None]
            else:
                raise FormulatorError("non-numeric target: declare `target_level` (the level whose rate is scanned)")
        else:
            if baseline_predictions is None or len(baseline_predictions) != len(rows):
                raise FormulatorError("baseline_error needs one baseline out-of-fold dev prediction per data row, "
                                      "in row order")
            if grammar.error == "mismatch":
                out[kind] = [1.0 if p != y else 0.0 for p, y in zip(baseline_predictions, y_raw, strict=True)]
            else:
                errs = []
                for p, y in zip(baseline_predictions, y_raw, strict=True):
                    pv, yv = _num(p), _num(y)
                    if pv is None or yv is None:
                        raise FormulatorError("absolute baseline error needs numeric predictions and labels")
                    errs.append(abs(pv - yv))
                out[kind] = errs
    return out


@dataclass
class _Scale:
    n: int
    total: float
    var: float


def _stat(s: float, m: int, sc: _Scale) -> float:
    """Pooled two-sample z of the cell mean against the rest. The pooled variance is the response's own, which a
    permutation leaves unchanged, so the null distribution of the max is exactly the permutation one."""
    rest = sc.n - m
    return (s / m - (sc.total - s) / rest) / math.sqrt(sc.var * (1 / m + 1 / rest))


def _signed(kind: str, z: float) -> float:
    # target: two-sided (a shift either way is an anomaly); baseline_error: one-sided (MORE error is an open problem)
    return abs(z) if kind == "target" else z


# ---------------------------------------------------------------- outputs
class CandidateProblem(_Frozen):
    """A typed candidate problem: a HYPOTHESIS mined from dev, never evidence. To be pursued it becomes ONE
    pre-registered claim against one held-out alpha slot."""

    id: str
    kind: Literal["subgroup_shift", "baseline_error_pocket"]
    response: ResponseKind
    conditions: tuple[Condition, ...]
    description: str
    n_cell: int
    n_dev: int
    effect: float  # cell mean - rest mean, in response units (dev)
    z: float
    p_scan: float  # permutation-max adjusted over the whole declared scan
    value: float
    feasibility: float
    tier: int
    tier_weight: float
    priority: float
    grammar_digest: str
    scan_size: int
    dev_dataset_id: str | None = None
    status: Literal["hypothesis"] = "hypothesis"
    note: str = ("mined on dev only; not evidence. Confirm with ONE pre-registered claim on held-out data "
                 "(trials factor 1 at confirmation; the scan's multiplicity was paid on dev)")


class FormulationResult(_Frozen):
    grammar_digest: str
    n_dev: int
    scan_size: int  # M = scannable cells x responses
    excluded_cells: int  # generated but below min_cell (or above n - min_cell)
    permutations: int
    alpha: float
    # a cell is a candidate iff its statistic is STRICTLY above this permutation maximum (None: no statistic can
    # reach p <= alpha with this B; the same bar for every response, since the maximum runs over the whole scan)
    threshold: float | None
    max_null: tuple[float, ...]  # the B permutation maxima (for audit)
    candidates: tuple[CandidateProblem, ...]  # sorted by priority, then p_scan, then id
    dev_dataset_id: str | None = None
    grammar_seq: int | None = None  # ledger seq of the grammar commitment (vault path)


def _feasibility(effect: float, m: int, n: int, var: float, n_confirm: int, confirm_alpha: float) -> float:
    nd = statistics.NormalDist()
    f = m / n
    se = math.sqrt(var * (1 / (f * n_confirm) + 1 / ((1 - f) * n_confirm)))
    return nd.cdf(abs(effect) / se - nd.inv_cdf(1 - confirm_alpha)) if se > 0 else 0.0


def formulate(grammar: CellGrammar, header: list[str], rows: list[list[str]], *,
              baseline_predictions: list[str] | None = None, tier: Tier = Tier.T6_NONE,
              n_confirm: int | None = None, dev_dataset_id: str | None = None, grammar_seq: int | None = None,
              config: L4Config = DEFAULTS) -> FormulationResult:
    """Scan DEV rows through the declared grammar; return the candidates that survive the permutation-max null."""
    grammar = _revalidate(grammar)
    n = len(rows)
    if n < 2 * grammar.min_cell:
        raise FormulatorError(f"{n} dev rows: too few for cells of at least {grammar.min_cell} rows and their rest")
    if any(len(r) != len(header) for r in rows):
        raise FormulatorError("ragged rows")
    resp = _responses(grammar, header, rows, baseline_predictions)
    cells, excluded = enumerate_cells(grammar, header, rows)
    if len(cells) * len(resp) > config.max_cells:
        raise FormulatorError(f"the grammar generates {len(cells) * len(resp)} scan cells (> {config.max_cells})")
    scales = {k: _Scale(n, sum(r), statistics.pvariance(r)) for k, r in resp.items()}
    live = [k for k in resp if scales[k].var > 0]  # a constant response has no anomaly (and no z)
    scan_size = len(cells) * len(resp)

    def scan_max(vectors: dict[ResponseKind, list[float]]) -> float:
        best = -math.inf
        for k in live:
            v, sc = vectors[k], scales[k]
            for c in cells:
                best = max(best, _signed(k, _stat(sum(v[i] for i in c.members), len(c.members), sc)))
        return best

    rng = random.Random(f"formulator:{grammar.digest()}:{grammar.seed}")
    order = list(range(n))
    maxima = []
    for _ in range(grammar.permutations):
        rng.shuffle(order)  # one permutation of the ROWS, shared by every response (their joint law is kept)
        maxima.append(scan_max({k: [resp[k][j] for j in order] for k in live}) if live else -math.inf)
    srt = sorted(maxima, reverse=True)
    # p <= alpha  <=>  #{max_b >= t} <= allowed  <=>  t > the (allowed + 1)-th largest permutation maximum
    allowed = math.floor(grammar.alpha * (grammar.permutations + 1) + 1e-9) - 1
    thr = None if allowed < 0 or not live else srt[allowed]
    tw = config.tier_weights[int(tier)]
    gd = grammar.digest()
    out: list[CandidateProblem] = []
    for k in live:
        sc, v = scales[k], resp[k]
        for c in cells:
            m = len(c.members)
            s = sum(v[i] for i in c.members)
            z = _stat(s, m, sc)
            t = _signed(k, z)
            p = (1 + sum(1 for x in maxima if x >= t)) / (grammar.permutations + 1)
            if p > grammar.alpha:
                continue
            effect = s / m - (sc.total - s) / (n - m)
            f = m / n
            if k == "baseline_error" and grammar.error == "mismatch":
                value = f * max(0.0, effect)
                kind: Literal["subgroup_shift", "baseline_error_pocket"] = "baseline_error_pocket"
                desc = (f"the baseline's dev error rate where {c.key} is {s / m:.3f} vs {(sc.total - s) / (n - m):.3f} "
                        f"elsewhere ({m} of {n} rows)")
            else:
                value = f * (1 - f) * effect * effect / sc.var
                kind = "baseline_error_pocket" if k == "baseline_error" else "subgroup_shift"
                desc = (f"mean {k} where {c.key} is {s / m:.4g} vs {(sc.total - s) / (n - m):.4g} elsewhere "
                        f"({m} of {n} rows)")
            feas = _feasibility(effect, m, n, sc.var, n_confirm or n, config.confirm_alpha)
            cid = "fp-" + hashlib.sha256(f"{gd}|{k}|{c.key}".encode()).hexdigest()[:12]
            out.append(CandidateProblem(
                id=cid, kind=kind, response=k, conditions=c.conditions, description=desc, n_cell=m, n_dev=n,
                effect=effect, z=z, p_scan=p, value=min(1.0, value), feasibility=feas, tier=int(tier),
                tier_weight=tw, priority=tw * min(1.0, value) * feas, grammar_digest=gd, scan_size=scan_size,
                dev_dataset_id=dev_dataset_id))
    out.sort(key=lambda c: (-c.priority, c.p_scan, -abs(c.z), c.id))
    return FormulationResult(grammar_digest=gd, n_dev=n, scan_size=scan_size, excluded_cells=excluded,
                             permutations=grammar.permutations, alpha=grammar.alpha,
                             threshold=thr, max_null=tuple(maxima), candidates=tuple(out),
                             dev_dataset_id=dev_dataset_id, grammar_seq=grammar_seq)


# ---------------------------------------------------------------- verifier tier (from the adapter registry only)
#: The strongest tier a claim of each evidence class can reach WHEN a human-approved adapter serves it (GOAL §4.7).
#: Simulated claims hold "T1/T2 within the simulator": the weaker one is used (conservative). A class with no
#: approved adapter gets T6 whatever this table says: the tier is never read from a model or a proposal.
CLASS_TIER: dict[str, Tier] = {"formal": Tier.T0_FORMAL, "computational": Tier.T1_EXECUTABLE,
                               "data": Tier.T2_STATISTICAL, "simulated": Tier.T2_STATISTICAL,
                               "physical": Tier.T3_PHYSICAL}


def best_available_tier_for(ledger: Any, evidence_class: str, metric: str | None = None) -> Tier:
    """The class's tier if a human-approved adapter serves (class, metric) NOW (K1's own `adapters.resolve`), else
    T6. With metric None, any metric a registered adapter of that class declares will do."""
    from ..kernel import EvidenceClass
    from ..kernel.adapters import REGISTRY, resolve
    cls = EvidenceClass(evidence_class)
    metrics = [metric] if metric is not None else sorted(
        {m for spec, _ in REGISTRY.values() if cls in spec.classes for m in spec.metrics})
    for m in metrics:
        adapter, _ = resolve(ledger, cls, m)
        if adapter is not None:
            return CLASS_TIER[cls.value]
    return Tier.T6_NONE


def best_available_tier(ledger: Any, metric: str) -> Tier:
    """T2 if a human-approved adapter serves data claims on `metric` now (K1's resolve), else T6."""
    return best_available_tier_for(ledger, "data", metric)


